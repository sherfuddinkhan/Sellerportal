import React, { useState } from "react";
import axios from "axios";
import { useNavigate } from "react-router-dom";

import {
    Alert,
    Box,
    Paper,
    Typography,
    TextField,
    Button,
    Grid,
    FormControl,
    InputLabel,
    Select,
    MenuItem,
    Divider,
    CircularProgress,
    Breadcrumbs,
    Link
} from "@mui/material";

import {
    Save,
    ArrowBack,
    PersonAdd,
    Clear
} from "@mui/icons-material";

// =========================================================
// API CONFIGURATION
// =========================================================

const SUPPLIER_CONTACT_API =
    "http://localhost:5000/api/supplier-contacts";

// =========================================================
// INITIAL FORM DATA
// =========================================================

const initialFormData = {
    contactType: "PRIMARY",
    name: "",
    contactName: "",
    email: "",
    phone: "",
    sellerId: "6",
    customerId: "3"
};

// =========================================================
// CREATE SUPPLIER CONTACT
// =========================================================

function SupplierContactCreate({
    onCreated,
    onCancel,
    onBack,
    title = "Create Supplier Contact"
}) {
    const navigate = useNavigate();

    const [formData, setFormData] = useState(initialFormData);
    const [saving, setSaving] = useState(false);
    const [error, setError] = useState("");
    const [fieldErrors, setFieldErrors] = useState({});

    // =====================================================
    // HANDLE INPUT CHANGE
    // =====================================================

    const handleChange = (event) => {
        const { name, value } = event.target;

        setFormData((previous) => ({
            ...previous,
            [name]: value,
            ...(name === "name" ? { contactName: value } : {}),
            ...(name === "contactName" ? { name: value } : {})
        }));

        setFieldErrors((previous) => ({
            ...previous,
            [name]: "",
            ...(name === "name" ? { contactName: "" } : {}),
            ...(name === "contactName" ? { name: "" } : {})
        }));

        setError("");
    };

    // =====================================================
    // VALIDATION
    // =====================================================

    const validateForm = () => {
        const errors = {};

        if (!formData.contactType) {
            errors.contactType = "Please select a contact type.";
        }

        if (!formData.name.trim()) {
            errors.name = "Name is required.";
        }

        if (!formData.contactName.trim()) {
            errors.contactName = "Contact name is required.";
        }

        if (!formData.email.trim()) {
            errors.email = "Email address is required.";
        } else if (
            !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(
                formData.email.trim()
            )
        ) {
            errors.email = "Enter a valid email address.";
        }

        if (!formData.phone.trim()) {
            errors.phone = "Phone number is required.";
        } else if (
            !/^[+]?[0-9\s()-]{7,20}$/.test(
                formData.phone.trim()
            )
        ) {
            errors.phone = "Enter a valid phone number.";
        }

        if (
            !Number.isInteger(Number(formData.sellerId)) ||
            Number(formData.sellerId) <= 0
        ) {
            errors.sellerId = "Enter a valid Seller ID.";
        }

        if (
            !Number.isInteger(Number(formData.customerId)) ||
            Number(formData.customerId) <= 0
        ) {
            errors.customerId = "Enter a valid Customer ID.";
        }

        setFieldErrors(errors);

        return Object.keys(errors).length === 0;
    };

    // =====================================================
    // CLEAR FORM
    // =====================================================

    const handleReset = () => {
        setFormData(initialFormData);
        setFieldErrors({});
        setError("");
    };

    // =====================================================
    // CANCEL / BACK
    // =====================================================

    const handleCancel = () => {
        if (onCancel) {
            onCancel();
        } else if (onBack) {
            onBack();
        } else {
            navigate("/supplier-contacts");
        }
    };

    // =====================================================
    // CREATE CONTACT
    // =====================================================
const handleSubmit = async (event) => {
    event.preventDefault();

    setError("");
    setFieldErrors({});

    if (!validateForm()) {
        return;
    }

    // Send fields entered by the user.
    // IDs and CreatedDate should be generated by the backend
    // if they are configured as server-generated fields.
    const payload = {
        contactType: formData.contactType,
        name: formData.name.trim(),
        contactName: formData.contactName.trim(),
        email: formData.email.trim(),
        phone: formData.phone.trim(),
        sellerId: Number(formData.sellerId),
        customerId: Number(formData.customerId)
    };

    try {
        setSaving(true);

        console.log("Creating supplier contact:", payload);

        const response = await axios.post(
            SUPPLIER_CONTACT_API,
            payload,
            {
                headers: {
                    "Content-Type": "application/json"
                }
            }
        );

        console.log(
            "SUPPLIER CONTACT CREATED:",
            response.data
        );

        if (onCreated) {
            onCreated(response.data || payload);
        } else {
            navigate("/supplier-contacts", {
                replace: true,
                state: {
                    message: "Supplier contact created successfully.",
                    severity: "success"
                }
            });
        }
    } catch (err) {
        const responseData = err.response?.data;

        console.error(
            "CREATE SUPPLIER CONTACT ERROR:",
            responseData || err.message
        );

        console.error(
            "HTTP STATUS:",
            err.response?.status
        );

        console.error(
            "REQUEST PAYLOAD:",
            payload
        );

        if (responseData?.errors) {
            const validationErrors = {};

            Object.entries(responseData.errors).forEach(
                ([key, messages]) => {
                    const normalizedKey =
                        key.charAt(0).toLowerCase() +
                        key.slice(1);

                    validationErrors[normalizedKey] =
                        Array.isArray(messages)
                            ? messages.join(" ")
                            : String(messages);
                }
            );

            setFieldErrors(validationErrors);
        }

        setError(
            responseData?.message ||
            responseData?.title ||
            responseData?.detail ||
            (typeof responseData === "string"
                ? responseData
                : "Failed to create supplier contact. Check the ASP.NET Core error log.")
        );
    } finally {
        setSaving(false);
    }
};


    // =====================================================
    // UI
    // =====================================================
return (
    <Box sx={{ p: { xs: 1, sm: 2, md: 3 } }}>
        {/* Header */}
        <Box
            sx={{
                display: "flex",
                justifyContent: "space-between",
                alignItems: { xs: "flex-start", sm: "center" },
                flexDirection: { xs: "column", sm: "row" },
                gap: 2,
                mb: 3
            }}
        >
            <Box>
                <Breadcrumbs sx={{ mb: 1 }}>
                    <Link
                        component="button"
                        type="button"
                        underline="hover"
                        color="inherit"
                        onClick={handleCancel}
                    >
                        Supplier Contacts
                    </Link>

                    <Typography color="text.primary">
                        Create
                    </Typography>
                </Breadcrumbs>

                <Typography variant="h5" fontWeight={700}>
                    {title}
                </Typography>

                <Typography
                    variant="body2"
                    color="text.secondary"
                    sx={{ mt: 0.5 }}
                >
                    Add a new supplier contact with all API fields.
                </Typography>
            </Box>

            <Button
                variant="outlined"
                startIcon={<ArrowBack />}
                onClick={handleCancel}
                disabled={saving}
            >
                Back
            </Button>
        </Box>

        {/* Error */}
        {error && (
            <Alert
                severity="error"
                sx={{ mb: 2 }}
                onClose={() => setError("")}
            >
                {error}
            </Alert>
        )}

        {/* Form Card */}
        <Paper
            elevation={2}
            sx={{ borderRadius: 2, overflow: "hidden" }}
        >
            <Box
                sx={{
                    p: 2.5,
                    display: "flex",
                    alignItems: "center",
                    gap: 1.5
                }}
            >
                <PersonAdd color="primary" />

                <Box>
                    <Typography variant="h6" fontWeight={600}>
                        Contact Information
                    </Typography>

                    <Typography
                        variant="body2"
                        color="text.secondary"
                    >
                        Enter all 11 fields from the API model.
                    </Typography>
                </Box>
            </Box>

            <Divider />

            <Box
                component="form"
                onSubmit={handleSubmit}
                noValidate
                sx={{ p: { xs: 2, sm: 3 } }}
            >
                <Grid container spacing={2.5}>
                    {/* 1. Party Contact ID */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="number"
                            label="Party Contact ID"
                            name="partyContactId"
                            value={formData.partyContactId ?? 0}
                            onChange={handleChange}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 2. Supplier ID */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="number"
                            label="Supplier ID"
                            name="supplierId"
                            value={formData.supplierId ?? 0}
                            onChange={handleChange}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 3. Contact Type */}
                    <Grid xs={12} md={6}>
                        <FormControl
                            fullWidth
                            required
                            error={Boolean(fieldErrors.contactType)}
                            disabled={saving}
                        >
                            <InputLabel>Contact Type</InputLabel>

                            <Select
                                name="contactType"
                                value={formData.contactType ?? ""}
                                label="Contact Type"
                                onChange={handleChange}
                            >
                                <MenuItem value="PRIMARY">
                                    Primary
                                </MenuItem>
                                <MenuItem value="SECONDARY">
                                    Secondary
                                </MenuItem>
                                <MenuItem value="BILLING">
                                    Billing
                                </MenuItem>
                                <MenuItem value="SHIPPING">
                                    Shipping
                                </MenuItem>
                                <MenuItem value="OTHER">
                                    Other
                                </MenuItem>
                            </Select>

                            {fieldErrors.contactType && (
                                <Typography
                                    variant="caption"
                                    color="error"
                                >
                                    {fieldErrors.contactType}
                                </Typography>
                            )}
                        </FormControl>
                    </Grid>

                    {/* 4. Name */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            label="Name"
                            name="name"
                            value={formData.name ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.name)}
                            helperText={fieldErrors.name}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 5. Contact Name */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            label="Contact Name"
                            name="contactName"
                            value={formData.contactName ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.contactName)}
                            helperText={fieldErrors.contactName}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 6. Email */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="email"
                            label="Email Address"
                            name="email"
                            value={formData.email ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.email)}
                            helperText={fieldErrors.email}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 7. Phone */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            label="Phone Number"
                            name="phone"
                            value={formData.phone ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.phone)}
                            helperText={fieldErrors.phone}
                            disabled={saving}
                        />
                    </Grid>

                    {/* 8. Seller ID */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="number"
                            label="Seller ID"
                            name="sellerId"
                            value={formData.sellerId ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.sellerId)}
                            helperText={fieldErrors.sellerId}
                            disabled={saving}
                            inputProps={{ min: 1 }}
                        />
                    </Grid>

                    {/* 9. Customer ID */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="number"
                            label="Customer ID"
                            name="customerId"
                            value={formData.customerId ?? ""}
                            onChange={handleChange}
                            error={Boolean(fieldErrors.customerId)}
                            helperText={fieldErrors.customerId}
                            disabled={saving}
                            inputProps={{ min: 1 }}
                        />
                    </Grid>

                    {/* 10. Created Date */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            label="Created Date"
                            name="createdDate"
                            type="datetime-local"
                            value={formData.createdDate ?? ""}
                            onChange={handleChange}
                            disabled={saving}
                            InputLabelProps={{ shrink: true }}
                        />
                    </Grid>

                    {/* 11. Supplier Contact ID */}
                    <Grid xs={12} md={6}>
                        <TextField
                            fullWidth
                            type="number"
                            label="Supplier Contact ID"
                            name="supplierContactId"
                            value={formData.supplierContactId ?? 0}
                            onChange={handleChange}
                            disabled={saving}
                        />
                    </Grid>

                    {/* Action Buttons */}
                    <Grid xs={12}>
                        <Divider sx={{ my: 1 }} />

                        <Box
                            sx={{
                                display: "flex",
                                justifyContent: "flex-end",
                                flexWrap: "wrap",
                                gap: 1.5,
                                mt: 2
                            }}
                        >
                            <Button
                                variant="outlined"
                                color="inherit"
                                startIcon={<Clear />}
                                onClick={handleReset}
                                disabled={saving}
                            >
                                Clear
                            </Button>

                            <Button
                                variant="outlined"
                                startIcon={<ArrowBack />}
                                onClick={handleCancel}
                                disabled={saving}
                            >
                                Cancel
                            </Button>

                            <Button
                                type="submit"
                                variant="contained"
                                startIcon={
                                    saving
                                        ? (
                                            <CircularProgress
                                                size={18}
                                                color="inherit"
                                            />
                                        )
                                        : <Save />
                                }
                                disabled={saving}
                            >
                                {saving
                                    ? "Saving..."
                                    : "Create Contact"}
                            </Button>
                        </Box>
                    </Grid>
                </Grid>
            </Box>
        </Paper>
    </Box>
);

}

export default SupplierContactCreate;
